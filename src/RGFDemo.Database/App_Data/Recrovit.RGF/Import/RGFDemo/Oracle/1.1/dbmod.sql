CREATE OR REPLACE VIEW v_employee AS
    SELECT
        CONCAT(CONCAT(e1.FirstName, ' '), e1.LastName) AS EmployeeName,
        (SELECT COUNT(*) FROM orders WHERE EmployeeID = e1.EmployeeID) AS OrdersCount,
        e1.*
    FROM Employees e1;
/
